// 변형 데이터 전체를 그대로 넘긴다 — 랜딩(직무 한 줄)은 DOM 쪽 일이라 main.js 가 집는다.
export const VARIANT_DATA = VARIANT ? VARIANTS[VARIANT] : null
if (VARIANT_DATA?.premises) {
  // 같은 객체를 덮어쓴다 — PREMISES 의 참조를 이미 들고 있는 world.js·main.js 가
  // 다시 읽을 필요 없이 그대로 바뀐 값을 본다.
  for (const [id, patch] of Object.entries(VARIANT_DATA.premises)) {
    const target = PREMISES.find((p2) => p2.id === id)
    if (target) Object.assign(target, patch)
  }
}
if (VARIANT) console.info(`[story] 변형 '${VARIANT}' 적용 — ${Object.keys(VARIANT_DATA).join(', ')}`)

// STOP_LABELS·PANEL_IN·PANEL_OUT 삭제(2026-08-15).
// STOP_LABELS('첫 번째 자리')는 한 자리를 부르는 세 번째 이름이었는데 어디서도 안 쓰였다 —
// main.js 가 MEET_LABELS 로 이름만 바꿔 받고 참조가 없었다. 지금 그 자리의 이름은 '01 · 시작' 하나다.
// PANEL_IN/OUT 은 import 만 되고 쓰이지 않았다(패널 노출은 meets[].state 가 정한다).

// ── 글자 수 예산 (한글, 공백 포함) ──
//   premise 20~36 / conclusion 18~60(화면에 안 뜸) / beats 한 조각 20~78(표준 34~62)
// 조각 분할선은 <br> 이다. 끊는 자리 우선순위: ① 문장 끝 ② 나열 쉼표 ③ 역접·인과 접속 앞.
// 어미 중간·조사 뒤에서는 끊지 않는다. 예산 초과는 글이 아니라 크기로 흡수한다(#verdict.long).
const COUNT = (t) => [...String(t).replace(/<br>/g, '')].length
if (import.meta.env?.DEV) {
  for (const p of PREMISES) {
    const chk = (name, v, lo, hi) => {
      const n = COUNT(v)
      if (n < lo || n > hi) console.warn(`[story] ${p.id}.${name} ${n}자 (예산 ${lo}~${hi})`)
    }
    chk('premise', p.premise, 20, 36)
    chk('conclusion', p.conclusion, 18, 60) // 화면에 안 뜨므로 상한이 느슨하다
    p.beats.forEach((b, i) =>
      String(b.text).split('<br>').forEach((line, j) => chk(`beats[${i}].${j}`, line, 12, 78))
    )
  }
}
